/** Numéro de compte de la comptabilité générale OHADA (classes 1 à 8). */
export const isValidAccount = (code) => /^[1-8][0-9]{1,7}$/.test(String(code || ""));

/** Intitulé officiel d'un compte : correspondance exacte, sinon la racine la plus longue connue. */
export function accountName(code) {
  const value = String(code);
  for (let length = value.length; length >= 1; length -= 1) {
    const name = ACCOUNTS[value.slice(0, length)];
    if (name) return length === value.length ? name : `${name} (${value})`;
  }
  return CLASSES[value[0]] ? `${CLASSES[value[0]]} (${value})` : `Compte ${value}`;
}

export const accountClass = (code) => Number(String(code)[0]);

